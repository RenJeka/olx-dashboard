// Спільні фрагменти промптів РУЧНОГО (ZIP) режиму — уніфікують три кроки AI-флоу:
//   1) AI Фільтр (relevance.ts), 2) Плюси/Мінуси (prompts.ts), 3) AI Вибір (aiPicks.ts).
// Спільний патерн агента: МЕХАНІЧНА процедура на файлах — map по чанках у проміжні файли →
// reduce → `output.json` → користувач вставляє ВМІСТ output.json у застосунок. Нічого в консоль.
// НЕ дублювати ці рядки в білдерах кроків — компонувати звідси (docs/ai-flow.md).

/** Єдина назва файлу результату для всіх кроків (агент або скрипт пише сюди). */
export const OUTPUT_FILE = 'output.json';

/**
 * Заголовок «механічна процедура» + єдине змістове завдання кроку.
 * `chunked` — для кроків, де агент сам обробляє `descriptions/chunk-NNN.json` по одному
 * (AI Фільтр, AI Вибір); крок Плюси/Мінуси віддає чанки готовому движку, тож без цього.
 */
export function mechanicalIntro(soleTask: string, opts: { chunked?: boolean } = {}): string {
  const head = opts.chunked
    ? 'Це МЕХАНІЧНА процедура на файлах — НЕ дослідницька задача. Дані вже поділені на чанки.'
    : 'Це МЕХАНІЧНА процедура — НЕ дослідницька задача.';
  return [head, `Твоє ЄДИНЕ змістове завдання — ${soleTask}`].join('\n');
}

/** Блок «Вміст пакета:» зі списком файлів. */
export function packageContents(items: string[]): string {
  return ['Вміст пакета:', ...items.map((i) => `- ${i}`)].join('\n');
}

// ── Спільні пункти списку заборон (реюз між кроками) ──────────────────────────
export const FORBID_CONSOLE =
  'друкувати результат у консоль/відповідь — достатньо файлу `output.json`';
export const FORBID_RESEARCH =
  '«досліджувати» датасет, рахувати статистику, вичищати/оптимізувати точність';
export const FORBID_REPROCESS = 'обробляти той самий чанк двічі або пропускати оголошення';

/** Блок «СУВОРО ЗАБОРОНЕНО» зі списком пунктів. */
export function forbidden(items: string[]): string {
  return [
    'СУВОРО ЗАБОРОНЕНО (інакше завдання вважається проваленим):',
    ...items.map((i) => `- ${i}`),
  ].join('\n');
}

/** Фінальний рядок «встав ВМІСТ output.json у застосунок». */
export function resultLine(when = 'коли завдання виконано'): string {
  return `РЕЗУЛЬТАТ: ${when} — встав ВМІСТ \`${OUTPUT_FILE}\` у поле застосунку.`;
}

/**
 * Fallback для асистента, що НЕ вміє потрібної файлової дії (запуск коду / створення файлів):
 * зробити все за один прохід і повернути ОДИН JSON у відповідь.
 */
export function fallbackBlock(condition: string, action: string): string {
  return `── Fallback (ТІЛЬКИ ${condition}): ${action}`;
}
